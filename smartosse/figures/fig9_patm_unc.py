def make_fig9(
    ds,
    sigma_std_map=None,
    sigma_spread_map=None,
    sigma_spread=None,
    relcon_per_region=None,
    row2_data=None,
    figsize=(16, 13),
    cable_lonlat=None,
    landfacecolor='white',
):
    """Assemble the full 2x2 mosaic from already-loaded pieces: (a)/(b) maps
    on top, (c) combined timeseries + (d) grouped relcon bars on the bottom.

    Pass in sigma_std_map/sigma_spread_map/sigma_spread/relcon_per_region/
    row2_data explicitly (e.g. from the load_* functions above) rather than
    having this function load everything itself, so a notebook can load once
    and iterate on layout/styling quickly.

    sigma_std_map/sigma_spread_map (lat/lon, from gen_patm_uncertainty_fields.py
    via load_sigma_patm_std_map()/load_sigma_patm_spread_map()) drive panels
    (a)/(b), sharing one range/colorbar (SIGMA_MAP_KWARGS for levels/extend,
    SIGMA_MAP_CBAR_KWARGS for colorbar ticks) -- edit those module constants
    (not this function) to retune. sigma_spread (ASTE grid, from
    load_sigma_patm_spread()) is a separate load -- panel (c)'s grey band
    needs to index it at cable (tile, j, i) sensor locations, which the
    lat/lon map field can't do. relcon_per_region (from
    load_relcon_per_region()) drives panel (d)'s grouped bars.
    """
    sigma_std_map = sigma_std_map if sigma_std_map is not None else load_sigma_patm_std_map()
    sigma_spread_map = sigma_spread_map if sigma_spread_map is not None else load_sigma_patm_spread_map()
    sigma_spread = sigma_spread if sigma_spread is not None else load_sigma_patm_spread()
    relcon_per_region = relcon_per_region if relcon_per_region is not None else load_relcon_per_region()
    row2_data = row2_data if row2_data is not None else load_row2_data(ds, sigma_spread)

    if cable_lonlat is None:
        cable_lonlat = {r: (row2_data[r]['lons'], row2_data[r]['lats']) for r in REGIONS}

    # SPNA projection center, matching smartosse.plot.spna()'s defaults
    # (xmin=-80, xmax=10 -> central_longitude=-35; ymin=40, ymax=80 ->
    # central_latitude=60). Kept in sync by hand -- if spna()'s defaults
    # change, update here too.
    spna_proj = ccrs.LambertConformal(central_longitude=-35, central_latitude=60)

    fig = plt.figure(figsize=figsize)
    # 2 rows now (was 3: maps / per-cable timeseries / per-cable relcon) --
    # (c)/(d) replace the old 4+4 per-cable panels with one merged panel each.
    gs_outer = fig.add_gridspec(2, 1, height_ratios=[1.5, 1], hspace=0.3)

    # row 1: two maps, plain 1x2 split now that (g) is gone. wspace at 0 so
    # the two maps read as one wide comparison panel, not two separate ones
    # (some residual gap is inherent to cartopy's aspect-driven letterboxing
    # within each GeoAxes cell, not just the gridspec spacing -- closed below
    # via an explicit reposition once both maps are drawn).
    #
    # add_axes(rect) rather than add_subplot(subplotspec): axes made with
    # add_subplot stay tied to their SubplotSpec in this env's matplotlib
    # (3.4.3, pre Axes/Subplot unification) -- on every draw (incl. the
    # final savefig), SubplotBase.update_params() re-derives the "original"
    # box straight from the gridspec cell, silently undoing any manual
    # set_position() we do below. A plain add_axes() box has no subplotspec
    # to re-derive from, so a manual reposition sticks.
    gs_row1 = gs_outer[0].subgridspec(1, 2, wspace=0.0)
    rect_a = gs_row1[0, 0].get_position(fig).bounds
    rect_b = gs_row1[0, 1].get_position(fig).bounds
    row1_x0, _, row1_w, _ = gs_outer[0].get_position(fig).bounds
    row1_center = row1_x0 + row1_w / 2.  # full row-1 extent, i.e. same span row2/row3 sit in
    ax_a = fig.add_axes(rect_a, projection=spna_proj)
    ax_b = fig.add_axes(rect_b, projection=spna_proj)

    # decorate the map axes with spna()'s extent/land/gridlines (spna(ax=...)
    # applies its styling to an already-created GeoAxes rather than making a
    # new one, which is what lets this compose with the gridspec above).
    _, ax_a = spna(ax=ax_a, landfacecolor=landfacecolor)
    _, ax_b, gl_b = spna(ax=ax_b, landfacecolor=landfacecolor, return_gl=True)

    # (b) sits right next to (a) -- its own latitude labels would just
    # duplicate (a)'s, so hide them (longitude labels along the bottom stay).
    for label in gl_b[0]._labels:
        if 'N' in label.artist.get_text():
            label.artist.set_visible(False)

    # bottom row: (c) combined timeseries, (d) grouped relcon bars
    gs_row2 = gs_outer[1].subgridspec(1, 2, wspace=0.3)
    ax_c = fig.add_subplot(gs_row2[0, 0])
    ax_d = fig.add_subplot(gs_row2[0, 1])

    # (a)/(b) share one colorbar -- both add_colorbar=False here, one shared
    # horizontal colorbar built below from either mappable (same norm/levels).
    _, _, p_a = plot_sigma_patm_map(sigma_std_map, ax=ax_a, cable_lonlat=cable_lonlat,
                                     add_colorbar=False, **SIGMA_MAP_KWARGS)
    add_panel_label(ax_a, 'a', fontsize=60)

    plot_sigma_patm_map(sigma_spread_map, ax=ax_b, cable_lonlat=cable_lonlat,
                         add_colorbar=False, **SIGMA_MAP_KWARGS)
    add_panel_label(ax_b, 'b', fontsize=60)

    # gridspec wspace=0 above isn't enough on its own -- cartopy's set_extent
    # makes each GeoAxes shrink to its own aspect-correct box and *center*
    # that box within its allocated cell, so a visible gap remains on both
    # sides of the cell boundary even at wspace=0. Fix it directly: once
    # both maps are drawn (forcing that shrink to resolve), glue them
    # together and re-center *the pair* on row1's full extent (matching
    # row2/row3's center) rather than sliding (b) next to (a)'s own natural
    # position -- (a) alone is centered only within its half of row1, which
    # is *not* row1's overall center, so that naive glue left the whole
    # (a)+(b) block visibly off-center vs. rows 2/3 below. Setting position
    # with which='both' (the default) makes this the new *original* box too,
    # so the aspect machinery doesn't re-center it away on the next
    # draw/save.
    fig.canvas.draw()
    pos_a, pos_b = ax_a.get_position(), ax_b.get_position()
    map_gap = 0.005
    combined_width = pos_a.width + map_gap + pos_b.width
    new_x0 = row1_center - combined_width / 2.
    ax_a.set_position([new_x0, pos_a.y0, pos_a.width, pos_a.height])
    ax_b.set_position([new_x0 + pos_a.width + map_gap, pos_b.y0, pos_b.width, pos_b.height])

    # Build the shared colorbar via a manually-placed `cax` rather than
    # fig.colorbar(..., ax=[ax_a, ax_b]) -- the latter's automatic
    # space-stealing resize of its parent axes silently undid the sizing/
    # centering fix above (it shrank ax_a/ax_b well below the width just
    # computed, whether done before or after the fix). A manual cax, sized
    # relative to the now-final (pos_a, pos_b), can't feed back on them.
    cbar_width = 0.6 * combined_width   # matches the old shrink=0.6 fraction
    cbar_height = 0.015
    cbar_pad = 0.03
    cax = fig.add_axes([
        row1_center - cbar_width / 2., pos_a.y0 - cbar_pad - cbar_height,
        cbar_width, cbar_height,
    ])
    cbar_ab = fig.colorbar(p_a, cax=cax, orientation='horizontal', **SIGMA_MAP_CBAR_KWARGS)
    cbar_ab.ax.set_xlabel('[hPa]', fontsize=22, labelpad=2)  # nudged up (toward the colorbar) from mpl's default labelpad=4
    cbar_ab.ax.tick_params(labelsize=20)

    plot_patm_adjustment_combined(ax_c, row2_data, ylim=(-1, 3), label_fontsize=18, min_label_gap=0.3)
    add_panel_label(ax_c, 'c', fontsize=26, x=0.02, y=0.95)
    # bbox_to_anchor y nudged below the panel-label letter (y=0.95, ~0.87 or
    # lower for its own box height) so the two don't overlap -- they used to
    # sit on top of each other at plain loc='upper left'.
    ax_c.legend(handles=_row2_legend_handles(), fontsize=13, frameon=False,
                loc='upper left', bbox_to_anchor=(0.0, 0.87))

