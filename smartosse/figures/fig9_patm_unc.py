def get_cable_sensor_args(region, mo_str='201201', bp_dir=BP_DATA_DIR, nz=None):
    """tile/j/i sensor indices (dims='sensor') for one partial cable's synthetic bp file.

    Matches on `*_<region>.bin` (leading underscore) rather than `*<region>.bin`
    -- the latter also matches e.g. "..._allbutnorthsea.bin" for region="northsea".
    """
    pattern = os.path.join(bp_dir, BP_FNAME_PATTERN.format(mo_str=mo_str, region=region))
    matches = glob.glob(pattern)
    if not matches:
        raise FileNotFoundError(f'No SMART bp file found for region={region!r} matching {pattern}')
    if len(matches) > 1:
        raise ValueError(f'Ambiguous match for region={region!r}: {matches}')

    bp = read_aste_bin(matches[0], nz=nz)
    bp = bp.where(bp != -9999., 0.)
    tile, j, i = np.where((bp[0] != 0.) & (~np.isnan(bp[0])))
    return dict(
        tile=xr.DataArray(tile, dims='sensor'),
        j=xr.DataArray(j, dims='sensor'),
        i=xr.DataArray(i, dims='sensor'),
    )


def get_cable_lonlat(ds, sensor_args):
    """(lons, lats) at a cable's sensor locations, from the grid dataset."""
    return ds.XC.isel(**sensor_args).values, ds.YC.isel(**sensor_args).values


def load_patm_adjustment(run_dir_root, region, iternum=20, datetimes=None, reverse_time=True):
    """xx_apressure.effective control-adjustment knots [Pa] for one partial-cable run.

    Returns a DataArray with dims (time, tile, j, i). See the module docstring
    re: `reverse_time`.
    """
    fname = f'{run_dir_root}/{region}/iter{iternum:04d}/xx_apressure.effective.{iternum:010d}.data'
    xx = read_aste_bin(fname)
    xx = xx.rename({'k': 'time'})

    if datetimes is not None:
        nt = len(datetimes)
        xx = xx.isel(time=slice(0, nt))
        if reverse_time:
            xx = xx.isel(time=slice(None, None, -1))
        xx = xx.assign_coords(time=('time', pd.DatetimeIndex(datetimes)))
    return xx  # Pa


def _group_ctrl(da):
    """Collapse a `ctrl` coordinate (xx_uwind, xx_vwind, xx_apressure, ...) into
    winds / patm / other groups and sum over it."""
    group = xr.DataArray(
        np.select(
            [da.ctrl.isin(['xx_uwind', 'xx_vwind']), da.ctrl == 'xx_apressure'],
            ['winds', 'patm'],
            default='other',
        ),
        dims='ctrl',
        coords={'ctrl': da.ctrl},
        name='group',
    )
    return da.groupby(group).sum(dim='ctrl')


def load_relcon_grouped(run_dir, iternum=20, data_ctrl_dir=None, weight_dir=WEIGHT_DIR, nx=270):
    """Time-mean relative control contribution for one run dir, grouped winds/patm/other.

    Requires the `smartuq` package (ControlDataset). Returns an xr.DataArray
    with a single 'group' dim, summing to 1.
    """
    from smartuq.ctrl import ControlDataset

    cds = ControlDataset(
        f'{run_dir.rstrip("/")}/iter{iternum:04d}/',
        data_ctrl_dir=data_ctrl_dir,
        weight_dir=weight_dir,
        backend='aste',
        nx=nx,
        iternum=iternum,
    )
    return _group_ctrl(cds.ds.std_cost.mean('time'))


def load_relcon_std_spread(
    run_dir_root_std=RUN_DIR_ROOT_STD,
    run_dir_root_spread=RUN_DIR_ROOT_SPREAD,
    regions=REGIONS,
    iternum=20,
    weight_dir=WEIGHT_DIR,
    data_ctrl_dir_std=DATA_CTRL_DIR_STD,
    data_ctrl_dir_spread=DATA_CTRL_DIR_SPREAD,
):
    """Mean-over-region, time-mean relcon for the STD and SPREAD runs.

    Returns {'std': DataArray[group], 'spread': DataArray[group]}, each summing
    to 1 across 'group' (winds/patm/other). NB: std and spread runs use
    *different* data_ctrl_dir (their data.ctrl files point at different
    xx_apressure weight files) -- don't share one data_ctrl_dir across both.

    Backed the old single-mean "(g)" panel (plot_relcon_bars), now unused in
    make_fig9() in favor of the per-region row-3 bars (load_relcon_per_region
    / plot_relcon_bars_region) -- kept in case a basin-mean summary is useful
    again later.
    """
    configs = {'std': (run_dir_root_std, data_ctrl_dir_std),
               'spread': (run_dir_root_spread, data_ctrl_dir_spread)}
    out = {}
    for run_name, (root, ctrl_dir) in configs.items():
        per_region = [
            load_relcon_grouped(f'{root}/{region}/', iternum=iternum,
                                 data_ctrl_dir=ctrl_dir, weight_dir=weight_dir)
            for region in regions
        ]
        out[run_name] = xr.concat(
            per_region, dim=xr.DataArray(regions, dims='region')
        ).mean('region')
    return out


def load_relcon_per_region(
    run_dir_root_std=RUN_DIR_ROOT_STD,
    run_dir_root_spread=RUN_DIR_ROOT_SPREAD,
    regions=REGIONS,
    iternum=20,
    weight_dir=WEIGHT_DIR,
    data_ctrl_dir_std=DATA_CTRL_DIR_STD,
    data_ctrl_dir_spread=DATA_CTRL_DIR_SPREAD,
):
    """Per-region (not averaged), time-mean relcon for the STD and SPREAD
    runs -> row 3's per-cable bar pairs.

    Returns {'std': {region: DataArray[group]}, 'spread': {region:
    DataArray[group]}} -- same per-region values load_relcon_std_spread()
    averages away with .mean('region').
    """
    configs = {'std': (run_dir_root_std, data_ctrl_dir_std),
               'spread': (run_dir_root_spread, data_ctrl_dir_spread)}
    out = {}
    for run_name, (root, ctrl_dir) in configs.items():
        out[run_name] = {
            region: load_relcon_grouped(f'{root}/{region}/', iternum=iternum,
                                         data_ctrl_dir=ctrl_dir, weight_dir=weight_dir)
            for region in regions
        }
    return out


def compute_sigma_band_hpa(sigma_spread, sensor_args):
    """Scalar plausibility half-width [hPa] for one cable: mean SPREAD sigma
    across that cable's sensors."""
    return float(sigma_spread.isel(**sensor_args).mean()) / 100.


def load_row2_data(
    ds,
    sigma_spread,
    regions=REGIONS,
    mo_str='201201',
    iternum=20,
    run_dir_root_std=RUN_DIR_ROOT_STD,
    run_dir_root_spread=RUN_DIR_ROOT_SPREAD,
    bp_dir=BP_DATA_DIR,
    reverse_time=True,
):
    """Bundle everything plot_patm_adjustment_row() needs, per region.

    Returns {region: {'time', 'adj_std', 'adj_spread', 'sigma_band_hpa',
    'lons', 'lats'}}.
    """
    start = pd.to_datetime(mo_str, format='%Y%m')
    end = start + pd.offsets.MonthEnd(1)
    datetimes = pd.date_range(start=start, end=end, freq='D')

    out = {}
    for region in regions:
        sensor_args = get_cable_sensor_args(region, mo_str=mo_str, bp_dir=bp_dir, nz=len(datetimes))
        lons, lats = get_cable_lonlat(ds, sensor_args)

        adj_std = load_patm_adjustment(run_dir_root_std, region, iternum=iternum,
                                        datetimes=datetimes, reverse_time=reverse_time)
        adj_spread = load_patm_adjustment(run_dir_root_spread, region, iternum=iternum,
                                           datetimes=datetimes, reverse_time=reverse_time)

        out[region] = dict(
            time=datetimes,
            adj_std=adj_std.isel(**sensor_args),      # (time, sensor), Pa
            adj_spread=adj_spread.isel(**sensor_args),
            sigma_band_hpa=compute_sigma_band_hpa(sigma_spread, sensor_args),
            lons=lons,
            lats=lats,
        )
    return out


