def _month_day_formatter(x, pos=None):
    return mdates.num2date(x).strftime('%b\n%d')


def _style_time_axis(ax, time, yticks=(0, 1, 2), ylim=None, tick_labelsize=16):
    """Shared x/y-axis finishing for the row-2-style time series panels
    (month/day x ticks over the plotted month, y gridlines only at `yticks`).

    Factored out of plot_patm_adjustment_timeseries() so plot_patm_adjustment_combined()
    (panel (c), all 4 cables on one axes) can't drift out of sync with it.
    """
    ax.set_axisbelow(True)
    t0 = pd.to_datetime(np.asarray(time)[0])
    t1 = t0 + pd.offsets.MonthEnd(0)
    ax.set_xlim(t0, t1)
    ax.xaxis.set_major_formatter(ticker.FuncFormatter(_month_day_formatter))
    ax.tick_params(axis='x', rotation=0, labelsize=tick_labelsize)
    if yticks is not None:
        ax.set_yticks(yticks)   # ylim (incl. any dip below 0) is untouched -- just no tick/gridline there
    if ylim is not None:
        ax.set_ylim(*ylim)
    ax.grid(axis='y')
    ax.grid(axis='x', linestyle='--', alpha=0.5)


def plot_patm_adjustment_timeseries(
    ax,
    time,
    adj_std,          # (time, sensor) or (time,), Pa
    adj_spread,        # same
    sigma_band_hpa,    # scalar half-width [hPa], e.g. from compute_sigma_band_hpa
    pd_rms_hpa=PD_2003_RMS_HPA,
    color='k',
    symmetric_band=True,
    yticks=(0, 1, 2),   # only these get labeled/gridlined; ylim still dips below 0
    ylim=None,          # e.g. (-1, 3) to share one range across all row-2 panels
    tick_labelsize=16,  # x-axis (date) tick label size; every panel has an x-axis
    band_kwargs=None,
    pd_line_kwargs=None,
    std_line_kwargs=None,
    spread_line_kwargs=None,
):
    """One Fig-9 row-2 panel: STD (solid) vs SPREAD (dashed) |dp_atm| against
    the SPREAD-based plausibility band and the P&D 2003 RMS anchor (black,
    densely dotted).
    """
    # this env's matplotlib (3.4.3) predates pandas 2.x dropping `Index[:,
    # None]` -- ax.plot()/fill_between() on a raw pd.DatetimeIndex raises
    # "Multi-dimensional indexing... no longer supported". A plain
    # datetime64 ndarray plots fine either way.
    time = np.asarray(time)
    sensor_dim = 'sensor' if 'sensor' in adj_std.dims else None

    def _mean_abs_hpa(da):
        da = np.abs(da) / 100.
        return da.mean(sensor_dim) if sensor_dim else da

    std_kwargs = dict(color=color, label='STD', **STD_LINE_STYLE)
    std_kwargs.update(std_line_kwargs or {})
    spread_kwargs = dict(color=color, label='SPREAD', **SPREAD_LINE_STYLE)
    spread_kwargs.update(spread_line_kwargs or {})

    ax.plot(time, _mean_abs_hpa(adj_std), **std_kwargs)
    ax.plot(time, _mean_abs_hpa(adj_spread), **spread_kwargs)

    lo = -sigma_band_hpa if symmetric_band else 0.
    bk = dict(color='0.5', alpha=0.3, edgecolor='none', label=SIGMA_BAND_LABEL, zorder=0)
    bk.update(band_kwargs or {})
    ax.fill_between(time, lo, sigma_band_hpa, **bk)

    pk = dict(color='k', label='P&D 2003 (SPNA)', zorder=1, **PD_LINE_STYLE)
    pk.update(pd_line_kwargs or {})
    ax.axhline(pd_rms_hpa, **pk)

    _style_time_axis(ax, time, yticks=yticks, ylim=ylim, tick_labelsize=tick_labelsize)

    return ax


