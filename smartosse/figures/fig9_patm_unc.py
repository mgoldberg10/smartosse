def plot_relcon_bars_grouped(
    ax,
    relcon_per_region,   # {'std': {region: DataArray[group]}, 'spread': {region: DataArray[group]}}
    regions=REGIONS,
    region_labels=None,
    region_colors=None,
    shade_factors=None,
    group_order=RELCON_GROUP_ORDER,
    bar_width=0.32,
    pair_gap=0.04,
    spread_hatch='///',
    tick_fontsize=16,
    ylabel_fontsize=20,
    ylabel='relative contribution',
):
    """Panel (d): grouped STD/SPREAD relcon bars, one x-tick per cable
    (replaces the old row-3 4-panels-of-horizontal-bar-pairs layout).

    Color = cable identity, via region_group_colors()'s light/mid/dark shade
    of that cable's base color for other/winds/patm (dark = patm, the
    headline result) -- reuses the same REGION_COLORS as (a)/(b)/(c), so
    cable identity reads consistently across the whole figure. Hatch (not
    color, which is already spoken for) distinguishes STD (plain) from
    SPREAD (`spread_hatch`) within each cable's pair of bars.
    """
    region_labels = region_labels or REGION_LABELS
    region_colors = region_colors or REGION_COLORS

    x = np.arange(len(regions))
    half_step = (bar_width + pair_gap) / 2.
    std_x = x - half_step
    spread_x = x + half_step

    for xi_std, xi_spread, region in zip(std_x, spread_x, regions):
        colors = region_group_colors(region, region_colors, shade_factors)
        for xi, run_name, hatch in [(xi_std, 'std', None), (xi_spread, 'spread', spread_hatch)]:
            bottom = 0.
            da = relcon_per_region[run_name][region]
            for group in group_order:
                val = float(da.sel(group=group))
                ax.bar(xi, val, bar_width, bottom=bottom, color=colors[group],
                       edgecolor='k', linewidth=0.5, hatch=hatch)
                bottom += val

    ax.set_xticks(x)
    ax.set_xticklabels([latex_escape(f'{region_labels[r]}_cable') for r in regions], fontsize=tick_fontsize)
    ax.set_ylim(0, 1)
    ax.set_yticks([0, 0.5, 1])
    ax.tick_params(axis='y', labelsize=tick_fontsize)
    ax.set_ylabel(ylabel, fontsize=ylabel_fontsize)
    ax.grid(axis='y', alpha=0.3)
    ax.set_axisbelow(True)
    for spine in ('top', 'right'):
        ax.spines[spine].set_visible(False)

    return ax


