def load_sigma_patm(fname, weight_dir=WEIGHT_DIR):
    """ASTE-gridded p_atm uncertainty sigma [Pa] from a `w = sigma^-2` weight binary.

    Works for either prior -- pass SIGMA_STD_FNAME or SIGMA_SPREAD_FNAME (or
    any other wApressure_*.bin living in weight_dir).
    """
    w = read_aste_bin(os.path.join(weight_dir, fname))
    sigma = w ** -0.5
    return sigma.where(np.isfinite(sigma))  # Pa, land/zero-weight -> NaN


def load_sigma_patm_std(weight_dir=WEIGHT_DIR, fname=SIGMA_STD_FNAME):
    return load_sigma_patm(fname, weight_dir=weight_dir)


def load_sigma_patm_spread(weight_dir=WEIGHT_DIR, fname=SIGMA_SPREAD_FNAME):
    return load_sigma_patm(fname, weight_dir=weight_dir)


