def plot_sigma_patm_map(
    sigma,
    ax=None,
    cable_lonlat=None,     # dict[region] -> (lons, lats); omit to skip cable overlay
    region_colors=None,
    cmap='Greys',
    hpa=True,
    add_colorbar=True,
    cbar_kwargs=None,
    scatter_kwargs=None,
    **contourf_kwargs,
):
    """sigma_patm map on the SPNA projection, optionally with per-region cable markers.

    `sigma` is a lat/lon (JRA55-grid) DataArray in Pa, e.g. from
    load_sigma_patm_std_map()/load_sigma_patm_spread_map() -- these are
    plotted directly (xarray contourf + PlateCarree transform), unlike the
    ASTE-gridded weight-derived fields which need `ds.plotpc`. vmin/vmax/
    levels are left to xarray's own robust scaling unless passed via
    contourf_kwargs -- the STD and SPREAD fields differ by ~5-10x in
    magnitude, so a shared hardcoded range would make one panel look empty.
    """
    if ax is None:
        fig, ax = spna()
    else:
        fig = ax.figure

    field = sigma / 100. if hpa else sigma

    ck = dict(cmap=cmap, add_colorbar=False, transform=ccrs.PlateCarree(), robust=True)
    ck.update(contourf_kwargs)
    p = field.plot.contourf(ax=ax, **ck)

    cb = None
    if add_colorbar:
        cbk = dict(orientation='horizontal', shrink=0.8, pad=0.05)
        cbk.update(cbar_kwargs or {})
        cb = fig.colorbar(p, ax=ax, **cbk)
        cb.ax.set_xlabel('[hPa]' if hpa else '[Pa]', fontsize=16)

    if cable_lonlat is not None:
        region_colors = region_colors or REGION_COLORS
        sk = dict(s=20, edgecolor='w', linewidth=0.5, transform=ccrs.PlateCarree(), zorder=4)
        sk.update(scatter_kwargs or {})
        for region, (lons, lats) in cable_lonlat.items():
            ax.scatter(lons, lats, facecolor=region_colors.get(region, 'k'), **sk)

    return ax, cb, p


def plot_relcon_bars(
    relcon,
    ax=None,
    colors=None,
    group_order=RELCON_GROUP_ORDER,
    width=0.5,
    legend=True,
    **bar_kwargs,
):
    """Panel (g): stacked relcon bars, one bar per run (dict key), stacked by group.

    `relcon` : dict[str, xr.DataArray] with a 'group' dim (e.g. from
    load_relcon_std_spread()), values summing to ~1 per run.
    """
    if ax is None:
        fig, ax = plt.subplots(figsize=(2.4, 4))
    else:
        fig = ax.figure

    colors = colors or RELCON_GROUP_COLORS
    run_names = list(relcon.keys())
    x = np.arange(len(run_names))

    for xi, run_name in zip(x, run_names):
        bottom = 0.
        da = relcon[run_name]
        for group in group_order:
            val = float(da.sel(group=group))
            ax.bar(xi, val, width, bottom=bottom, color=colors[group],
                   edgecolor='k', linewidth=0.5, **bar_kwargs)
            bottom += val

    ax.set_xticks(x)
    ax.set_xticklabels(run_names)
    ax.set_ylim(0, 1)
    ax.set_ylabel('relative contribution')
    ax.grid(axis='y', alpha=0.3)

    if legend:
        handles = [Patch(facecolor=colors[g], edgecolor='k', label=g) for g in group_order]
        ax.legend(handles=handles, frameon=False, fontsize=9,
                  loc='upper center', bbox_to_anchor=(0.5, -0.12), ncol=1)

    return ax


def plot_relcon_bars_region(
    ax,
    relcon_std,       # DataArray[group], sums to 1
    relcon_spread,    # DataArray[group], sums to 1
    group_order=RELCON_GROUP_ORDER,
    colors=None,
    height=0.6,
    spread_hatch=None,
    tick_fontsize=16,
    ylabel_fontsize=None,
    **barh_kwargs,
):
    """Row 3: one region's STD/SPREAD relcon as a pair of horizontal stacked
    bars (STD above, SPREAD below), winds/patm/other, each summing to 1.

    The y-tick labels ('STD'/'SPREAD') are what distinguish the two rows;
    pass `spread_hatch` (e.g. '///') to also hatch SPREAD if the labels alone
    aren't enough (e.g. grayscale printing, cropped screenshot) -- off by
    default since it's redundant once the labels are legible. `ylabel_fontsize`
    (defaults to `tick_fontsize` if omitted) sets just the STD/SPREAD y-tick
    labels, independent of the x-tick (0/0.5/1) fontsize.
    """
    colors = colors or RELCON_GROUP_COLORS
    ylabel_fontsize = tick_fontsize if ylabel_fontsize is None else ylabel_fontsize

    for y, relcon, hatch in [(1, relcon_std, None), (0, relcon_spread, spread_hatch)]:
        left = 0.
