def _declutter_1d(values, min_gap):
    """Nudge `values` upward (preserving rank order) so consecutive sorted
    values are at least `min_gap` apart. Returns an array aligned to the
    *original* (unsorted) order of `values`.

    Used to keep panel (c)'s 4 end-of-line cable labels from overlapping
    where the curves converge (e.g. all 4 cables land within ~0.5 hPa of each
    other during the late-Jan spike, per STATUS.md).
    """
    values = np.asarray(values, dtype=float)
    order = np.argsort(values)
    adjusted = values.copy()
    for k in range(1, len(order)):
        i, prev = order[k], order[k - 1]
        if adjusted[i] - adjusted[prev] < min_gap:
            adjusted[i] = adjusted[prev] + min_gap
    return adjusted


def plot_patm_adjustment_combined(
    ax,
    row2_data,
    regions=REGIONS,
    region_labels=None,
    region_colors=None,
    sigma_band_hpa=None,
    pd_rms_hpa=PD_2003_RMS_HPA,
    yticks=(0, 1, 2),
    ylim=(-1, 3),
    tick_labelsize=16,
    ylabel='[hPa]',
    ylabel_fontsize=20,
    label_fontsize=16,
    min_label_gap=0.18,
    label_x=1.015,
    band_kwargs=None,
    pd_line_kwargs=None,
    std_line_kwargs=None,
    spread_line_kwargs=None,
):
    """Panel (c): all 4 cables' STD (solid) vs SPREAD (dashed) |dp_atm| on one
    shared axes, replacing the old 4-panels-per-region row.

    Color = cable identity (REGION_COLORS, matching (a)/(b)'s map dots and
    panel (d)'s bars). ONE shared +/-sigma_spread band (mean of the 4 cables'
    own bands -- they're all similar magnitude, see STATUS.md) and ONE P&D
    2003 line, both plotted un-colored (grey/black) since they're basin-wide
    references, not specific to any one cable.

    Cable identity is a direct end-of-line label at the STD curve's last
    value (decluttered via _declutter_1d so 4 converging curves don't
    overlap) rather than an 8-entry (4 cable x 2 linestyle) legend -- pass
    a separate small legend (e.g. _row2_legend_handles()) for the
    STD/SPREAD/band/P&D linestyle key, which is cable-agnostic.
    """
    region_labels = region_labels or REGION_LABELS
    region_colors = region_colors or REGION_COLORS

    time = np.asarray(row2_data[regions[0]]['time'])

    if sigma_band_hpa is None:
        sigma_band_hpa = float(np.mean([row2_data[r]['sigma_band_hpa'] for r in regions]))

    std_kwargs_base = dict(**STD_LINE_STYLE)
    std_kwargs_base.update(std_line_kwargs or {})
    spread_kwargs_base = dict(**SPREAD_LINE_STYLE)
    spread_kwargs_base.update(spread_line_kwargs or {})

    end_vals, end_colors = [], []
    for region in regions:
        d = row2_data[region]
        color = region_colors.get(region, 'k')
        sensor_dim = 'sensor' if 'sensor' in d['adj_std'].dims else None

        def _mean_abs_hpa(da):
            da = np.abs(da) / 100.
            return da.mean(sensor_dim) if sensor_dim else da

        std_vals = np.asarray(_mean_abs_hpa(d['adj_std']))
        spread_vals = np.asarray(_mean_abs_hpa(d['adj_spread']))

        ax.plot(time, std_vals, color=color, **std_kwargs_base)
        ax.plot(time, spread_vals, color=color, **spread_kwargs_base)

        end_vals.append(float(std_vals[-1]))
        end_colors.append(color)

    lo = -sigma_band_hpa
    bk = dict(color='0.5', alpha=0.3, edgecolor='none', label=SIGMA_BAND_LABEL, zorder=0)
    bk.update(band_kwargs or {})
    ax.fill_between(time, lo, sigma_band_hpa, **bk)

    pk = dict(color='k', label='P&D 2003 (SPNA)', zorder=1, **PD_LINE_STYLE)
    pk.update(pd_line_kwargs or {})
    ax.axhline(pd_rms_hpa, **pk)

    _style_time_axis(ax, time, yticks=yticks, ylim=ylim, tick_labelsize=tick_labelsize)

    # Direct end-of-line cable labels (axes-fraction x, data y so they sit
    # just past the right spine regardless of ylim) -- decluttered so they
    # don't collide where the 4 curves converge.
    label_ys = _declutter_1d(end_vals, min_label_gap)
    yaxis_transform = ax.get_yaxis_transform()
    for region, val, y, color in zip(regions, end_vals, label_ys, end_colors):
        if abs(y - val) > 1e-9:
            ax.plot([1.0, label_x - 0.005], [val, y], transform=yaxis_transform,
                    color=color, lw=0.8, clip_on=False, zorder=5)
        ax.annotate(
            region_labels[region], xy=(label_x, y), xycoords=('axes fraction', 'data'),
            color=color, fontsize=label_fontsize, fontweight='bold',
            va='center', ha='left', clip_on=False,
        )

    ax.set_ylabel(ylabel, fontsize=ylabel_fontsize)
    ax.tick_params(axis='y', labelsize=tick_labelsize)

    return ax


